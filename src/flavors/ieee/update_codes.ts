export function applyUpdateCodes(input: string): string {
  let code = input;
  for (const entry of UPDATE_CODES) {
    if (entry.plain !== undefined) {
      const anchored = new RegExp(`^${entry.plain.replace(/[.*+?^${}()|[\]\\]/g, "\\$&")}$`);
      // Plain keys substitute LITERALLY (Ruby String#gsub with a String
      // replacement treats it literally except backrefs, which plain keys
      // never carry); the replacer function keeps "$" safe.
      const literal = entry.replacement;
      code = code.replace(anchored, () => literal);
    } else if (entry.pattern !== undefined) {
      // Regex-literal keys may carry Ruby backrefs (\1) — map to $1.
      const replacement = entry.replacement.replace(/\\(\d)/g, (_, d: string) => `$${d}`);
      code = code.replace(new RegExp(entry.pattern, entry.flags), replacement);
    }
  }
  return code;
}
