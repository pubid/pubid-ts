#!/usr/bin/env node
// Writes src/parg/artifacts/<grammar>.ts for every grammar a flavor loads
// through PubidRuntime.load: the vendored artifact (vendor/parg) as the
// module's default export, its raw JSON text verbatim (the engine
// verifies the checksum over the exact text). A worker has no disk, so
// it imports these modules and registers them (dist/worker.js); node
// keeps reading vendor/parg. Run via `npm run artifact:modules` (and
// `npm run artifact`) after a vendor/parg refresh — test/worker-entry
// fails while a module is stale.
import { readFileSync, readdirSync, writeFileSync, mkdirSync, rmSync } from "node:fs";
import { join } from "node:path";

const grammars = new Set();
for (const flavor of readdirSync("src/flavors")) {
  let source;
  try {
    source = readFileSync(join("src/flavors", flavor, "index.ts"), "utf8");
  } catch {
    continue;
  }
  for (const m of source.matchAll(/PubidRuntime\.load\("([a-z_]+)"/g)) grammars.add(m[1]);
}

const outDir = "src/parg/artifacts";
rmSync(outDir, { recursive: true, force: true });
mkdirSync(outDir, { recursive: true });
const sorted = [...grammars].sort();
for (const grammar of sorted) {
  const json = readFileSync(join("vendor/parg", `${grammar}.json`), "utf8");
  writeFileSync(
    join(outDir, `${grammar}.ts`),
    `// Generated by scripts/build-artifact-modules.mjs from vendor/parg/${grammar}.json — do not edit.\n` +
      `const artifact: string = ${JSON.stringify(json)};\nexport default artifact;\n`,
  );
}
writeFileSync(
  join(outDir, "index.ts"),
  "// Generated by scripts/build-artifact-modules.mjs — do not edit.\n" +
    "/** The grammars the artifact-backed flavors load (PubidRuntime.load). */\n" +
    `export const PARG_GRAMMARS: readonly string[] = ${JSON.stringify(sorted)};\n`,
);
console.log(`artifact modules: ${sorted.length} grammars -> ${outDir}`);
