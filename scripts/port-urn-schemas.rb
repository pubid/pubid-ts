# frozen_string_literal: true

# (Re)generates the TS pubid-urn schema tables in src/pubid-urn/schemas/
# from the ruby declarations (pubid-ts#161; the tables are GENERATED,
# never hand-edited — see each file's header). For every committed table
# the matching ruby lib/pubid/<flavor>/pubid_urn_schema.rb is loaded from
# a pubid checkout and the FlavorSchema is serialized: flavor-level
# atoms, then facets, then one s.type per concrete type, mirroring the
# declare-then-derive order the encoder consumes.
#
#   ruby scripts/port-urn-schemas.rb <pubid-checkout> [schemas-dir]
#
# <pubid-checkout> is a pubid ruby checkout whose lib/ declares the
# PubidUrnSchema chain (main). [schemas-dir] defaults to
# src/pubid-urn/schemas. The committed table set (file names, export
# names, registry order in index.ts) is the authority: only the bodies
# are regenerated, so a flavor with no TS table yet is reported and
# skipped.
require "json"

PUBID_REF = ARGV[0] or
  raise "usage: ruby scripts/port-urn-schemas.rb <pubid-checkout> [schemas-dir]"
OUT = ARGV[1] ? File.expand_path(ARGV[1]) : File.expand_path("../src/pubid-urn/schemas", __dir__)

$LOAD_PATH.unshift File.expand_path("lib", PUBID_REF)
require "pubid"

# Capture every Pubid::PubidUrn.define call's result without reaching
# into the registry: the singleton prepend records what the loaded
# schema files return.
found = {}
Pubid::PubidUrn.singleton_class.prepend(Module.new do
  define_method(:define) do |flavor, &block|
    schema = super(flavor, &block)
    found[flavor] = schema
    schema
  end
end)

SCHEMA_FILES = Dir.glob(File.join(PUBID_REF, "lib", "pubid", "*", "pubid_urn_schema.rb")).sort
raise "no pubid_urn_schema.rb under #{PUBID_REF}/lib/pubid" if SCHEMA_FILES.empty?

SCHEMA_FILES.each { |file| load file }

HEADER = <<~HEAD
  /**
   * The pubid-scheme URN schema of %<flavor>s — the transcription
   * of lib/pubid/<flavor>/pubid_urn_schema.rb (pubid#656, completed by
   * #670; design in docs/URN-SCHEMES.adoc). GENERATED by
   * scripts/port-urn-schemas.rb from the ruby declaration: edit the ruby
   * schema and regenerate, never this table by hand.
   */
HEAD

def q(value)
  JSON.generate(value.to_s)
end

# The flavor-level atoms/facets every type carries: by construction each
# type's list is the flavor list followed by the type's own extras, so
# the declaration order is recovered as the common prefix.
def common_prefix(lists)
  first = lists.first || []
  shared = first.each_index.take_while do |i|
    lists.all? { |list| list[i] == first[i] }
  end
  first[0...shared.size]
end

def core_entry(path, kind)
  kind == :string ? q(path) : "[#{q(path)}, #{q(kind)}]"
end

def value_entry(path, name, kind)
  suffix = kind_suffix(path, kind)
  suffix.empty? ? "[#{q(path)}, #{q(name)}]" : "[#{q(path)}, #{q(name)}#{suffix}]"
end

def type_declaration(type)
  # The default core the DSL applies when `core:` is omitted.
  default_core = type.core.map(&:size) == [1] &&
                 type.core == [["number"]] && type.core_kinds == [:string]
  core = default_core ? nil : type.core.zip(type.core_kinds)
                     .map { |pair| core_entry(pair[0].join("."), pair[1]) }
  atoms = type.atoms.drop(@flavor_atoms.size)
  facets = type.facets.drop(@flavor_facets.size)

  options = {}
  options["core"] = core if core
  options["atoms"] = atoms.map { |a| value_entry(a.path, a.prefix, a.kind) } unless atoms.empty?
  options["facets"] = facets.map { |f| value_entry(f.path, f.name, f.kind) } unless facets.empty?
  options
end

def kind_suffix(path, kind)
  # The DSL resolves a "*" path to :list, so the redundant kind is
  # omitted there exactly as it defaults elsewhere to :string.
  default = path.split(".").include?("*") ? :list : :string
  kind == default ? "" : ", #{q(kind)}"
end

def render(schema, export_base)
  types = schema.types.values
  raise "#{schema.flavor}: no types declared" if types.empty?

  @flavor_atoms = common_prefix(types.map(&:atoms))
  @flavor_facets = common_prefix(types.map(&:facets))

  lines = []
  lines << format(HEADER, flavor: schema.flavor.upcase).chomp
  lines << ""
  lines << ""
  lines << 'import { define } from "../index.js";'
  lines << ""
  lines << "export const #{export_base}Schema = define(#{q(schema.flavor)}, (s) => {"

  groups = []
  groups << @flavor_atoms.map do |atom|
    "  s.atom(#{q(atom.path)}, #{q(atom.prefix)}#{kind_suffix(atom.path, atom.kind)});"
  end
  groups << @flavor_facets.map do |facet|
    "  s.facet(#{q(facet.path)}, #{q(facet.name)}#{kind_suffix(facet.path, facet.kind)});"
  end unless @flavor_facets.empty?
  groups << types.map do |type|
    token = "  s.type(#{q(type.type)}, #{q(type.token)}"
    options = type_declaration(type)
    if options.empty?
      "#{token});"
    elsif options.size == 1
      key, value = options.first
      body = value.nil? ? "[]" : "[#{value.join(', ')}]"
      "#{token}, { #{key}: #{body} });"
    else
      # More than one option key wraps, one option per line.
      body = options.map do |key, value|
        body = value.nil? ? "[]" : "[#{value.join(', ')}]"
        "    #{key}: #{body},"
      end
      ([ "#{token}, {" ] + body + ["  });"]).join("\n")
    end
  end
  body = groups.reject(&:empty?).map { |group| Array(group).join("\n") }
               .join("\n\n")
  lines.concat(body.split("\n"))
  lines << "});"
  lines.join("\n") + "\n"
end

tables = Dir.glob(File.join(OUT, "*.ts")).reject { |f| File.basename(f) == "index.ts" }.sort
raise "no schema tables under #{OUT}" if tables.empty?

written = 0
tables.each do |file|
  body = File.read(file)
  flavor = body[/define\((\"[^\"]+\")/, 1]&.then { |s| JSON.parse(s) } or
    raise "#{file}: no define(<flavor>) declaration to match against ruby"
  export_base = body[/export const (\w+)Schema = define\(/, 1] or
    raise "#{file}: no export const <name>Schema to regenerate"
  schema = found[flavor] or
    raise "#{file}: flavor #{flavor.inspect} declares no PubidUrnSchema in #{PUBID_REF}"

  File.write(file, render(schema, export_base))
  written += 1
rescue StandardError => e
  warn "#{File.basename(file)}: skipped (#{e.class}: #{e.message})"
end

missing = found.keys - tables.map { |f| File.read(f)[/define\((\"[^\"]+\")/, 1] }.compact.map { |s| JSON.parse(s) }
warn "missing a TS table (declared in ruby, not committed here): #{missing.join(', ')}" unless missing.empty?
warn "regenerated #{written}/#{tables.size} tables from #{SCHEMA_FILES.size} ruby schemas"
