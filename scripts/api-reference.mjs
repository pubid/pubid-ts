#!/usr/bin/env node
// Generates docs/api-reference.md from TypeDoc's reflection of src/
// (pubid#577). Deterministic given the pinned typedoc version; CI
// regenerates and fails on drift.
import { Application, ReflectionKind } from "typedoc";
import { writeFileSync } from "node:fs";
import { resolve } from "node:path";

const app = await Application.bootstrap(
  {
    entryPoints: ["src/index.ts"],
    tsconfig: resolve("tsconfig.json"),
    // this typedoc does not apply the tsconfig's compilerOptions to its
    // own program — restate the ones the sources need.
    compilerOptions: {
      target: "ES2022",
      module: "Node16",
      moduleResolution: "Node16",
      strict: true,
      skipLibCheck: true,
    },
    logLevel: "Warn",
  },
  [],
);
const project = await app.convert();
if (!project) {
  console.error("typedoc conversion failed");
  process.exit(1);
}

const METHOD = ReflectionKind.Method | ReflectionKind.Function;
const isCallable = (r) => (r.flags.isStatic ? "static " : "") && r;
const signature = (r) => {
  const sig = r.signatures?.[0];
  if (!sig) return r.name;
  const params = (sig.parameters ?? [])
    .map((p) => `${p.name}${p.flags.isOptional ? "?" : ""}`)
    .join(", ");
  return `${r.name}(${params})`;
};
const doc = (r) => {
  const sig = r.signatures?.[0] ?? r;
  const text = sig.comment?.summary
    ?.map((t) => t.text)
    .join("")
    .trim()
    .split("\n")[0];
  return text ? `\n${text}\n` : "\n";
};

const out = [
  "# API reference",
  "",
  "<!-- Generated by `npm run doc:api` (TypeDoc over src/) — do not edit",
  "     by hand; CI fails on drift. The website assembles this file into",
  "     the library reference. -->",
  "",
];

const entry = (r) => {
  const label = `${r.flags.isStatic ? "static " : ""}${signature(r)}`;
  return `### \`${label}\`${doc(r)}`;
};

for (const child of (project.children ?? [])
  .filter((c) =>
    [ReflectionKind.Class, ReflectionKind.Interface, ReflectionKind.Function]
      .includes(c.kind),
  )
  .sort((a, b) => a.name.localeCompare(b.name))) {
  out.push(`## \`${child.name}\``, "");
  const members = (child.children ?? [])
    .filter((m) =>
      [ReflectionKind.Method, ReflectionKind.Function].includes(m.kind) ||
      (child.kind === ReflectionKind.Interface &&
        m.kind === ReflectionKind.Property),
    )
    .sort((a, b) => a.name.localeCompare(b.name));
  for (const m of members) out.push(entry(m));
  out.push("");
}

writeFileSync("docs/api-reference.md", `${out.join("\n")}\n`);
console.log(
  `docs/api-reference.md: ${(out.join("\n").match(/^### /gm) ?? []).length} entries over ${project.children?.length ?? 0} root reflections`,
);
